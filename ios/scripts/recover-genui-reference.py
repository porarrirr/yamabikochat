#!/usr/bin/env python3
"""Recover GenUI componentSource strings, SVG assets and numeric/color contracts.

Usage: python3 ios/scripts/recover-genui-reference.py --analysis PATH --valdi PATH
Valdi checkout: https://github.com/Snapchat/Valdi (third-party/quickjs required).
Exported component source/data and the exact self-contained CEL module are bundled.
"""
import argparse, hashlib, json, re, struct, subprocess, tempfile
from pathlib import Path
import xml.etree.ElementTree as ET

parser = argparse.ArgumentParser()
parser.add_argument('--analysis', type=Path, required=True)
parser.add_argument('--valdi', type=Path, required=True)
args = parser.parse_args()
ios = Path(__file__).resolve().parent.parent
assets = ios / 'YamabikoChat/App/Resources/genui'
modules = args.analysis / 'valdimodule-contents'
quickjs = args.valdi / 'third-party/quickjs'

with tempfile.TemporaryDirectory(prefix='genui-recovery-') as directory:
    build = Path(directory)
    includes = ['-I'+str(quickjs / item) for item in ['include', 'include/quickjs', 'src/quickjs']]
    subprocess.run(['clang', '-O2', '-w', '-DCONFIG_BIGNUM', *includes, '-c', str(quickjs/'src/quickjs/libbf.c'), '-o', str(build/'libbf.o')], check=True)
    subprocess.run(['clang', '-O2', '-w', '-DCONFIG_VERSION="2021-03-27"', *includes,
        str(ios/'scripts/genui-reference/extract.c'),
        *[str(quickjs/'src/quickjs'/name) for name in ['quickjs.c','cutils.c','libregexp.c','libunicode.c']],
        str(build/'libbf.o'), '-lm', '-o', str(build/'extract')], check=True)

    def export(module, filename, expression='JSON.stringify(exports)'):
        process = subprocess.run([str(build/'extract'), str(modules/module/filename), expression], capture_output=True, text=True, check=True)
        if filename.endswith('.generated.js') and 'SOURCE_START' not in process.stdout: raise RuntimeError(filename + ': ' + repr(process.stdout) + repr(process.stderr))
        return process.stdout

    sources = {}
    for path in sorted((modules/'dil_generated_components.valdimodule').glob('src__restricted__components__*.generated.js')):
        output = export('dil_generated_components.valdimodule', path.name, '0')
        sources[path.name.removeprefix('src__restricted__components__').removesuffix('.generated.js')] = output.split('SOURCE_START\n', 1)[1].split('\nSOURCE_END', 1)[0]
    assert len(sources) == 283
    factory = ['/* Recovered componentSource exports from the user-supplied APK analysis.',
        '   Source expressions are preserved; platform hooks are supplied by runtime.js. */',
        '(function(global) {', 'const factories = {']
    for name, source in sources.items():
        factory.append(json.dumps(name)+': (DIL, GenUI, __dil, OpGenuiResolvedComponentBoundary) => ('+source+'),')
    factory.extend(['};','global.__GENUI_REFERENCE_COMPONENT_FACTORIES__ = factories;',
        'if (typeof module !== "undefined") module.exports = factories;',
        '})(typeof window === "undefined" ? globalThis : window);'])
    (assets/'reference-components.js').write_text('\n'.join(factory))

    catalog = {name: sorted(set(re.findall(r'\bprops\.([a-zA-Z_$][\w$]*)', source)) | {'__state','__resolutionId','fallback'}) for name, source in sources.items()}
    manifest = [{'name':name,'sourceSHA256':hashlib.sha256(source.encode()).hexdigest(),'properties':catalog[name],
        'stateFields': sorted(set(re.findall(r'\bstate\.([a-zA-Z_$][\w$]*)',source)))} for name,source in sources.items()]
    (ios/'GenUI-reference-components.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
    swift = 'import Foundation\n\n// Recovered componentSource contracts. Generated by scripts/recover-genui-reference.py.\nenum GenUIReferenceCatalog {\n    static let components: [String: [String]] = [\n'
    for name, keys in catalog.items(): swift += '        '+json.dumps(name)+': '+json.dumps(keys)+',\n'
    swift += '    ]\n\n    static let stateFields: [String: [String]] = [\n'
    for entry in manifest: swift += '        '+json.dumps(entry['name'])+': '+json.dumps(entry['stateFields'])+',\n'
    swift += '    ]\n}\n'
    (ios/'YamabikoChat/Features/Tools/GenUI/GenUIReferenceCatalog.swift').write_text(swift)

    colors = json.loads(export('dil_core.valdimodule','src__colors__DILColorsDefinition.js').splitlines()[-1])
    typography = json.loads(export('dil_text.valdimodule','src__rendering__DILTextTypography.js','JSON.stringify(exports.DIL_IOS_TYPOGRAPHY)').splitlines()[-1])
    sizes = '["3xs","2xs","xs","sm","md","lg","xl","2xl","3xl"]'
    select = json.loads(export('dil_widgets.valdimodule','src__widgets__DILSelectControlMetrics.js', 'JSON.stringify(Object.fromEntries('+sizes+'.map(size=>[size,exports.resolveDILSelectControlMetrics(size)])))').splitlines()[-1])
    controls = json.loads(export('dil_widgets.valdimodule','src__widgets__DILWidgetSizes.js','JSON.stringify(Object.fromEntries('+sizes+'.map(size=>[size,{height:exports.resolveDILControlHeight(size,"md"),fontSize:exports.resolveDILControlFontSize(size,"md"),textInput:exports.resolveDILTextInputMetrics(size),icon:exports.resolveDILIconSize(size),buttonIcon:exports.resolveDILButtonIconSize(size)}])))').splitlines()[-1])
    colors.update(typography=typography,selectMetrics=select,controlMetrics=controls)
    (assets/'reference-tokens.js').write_text('/* Exact palette, typography and metric exports from the supplied modules. */\n(function(global) { global.__GENUI_REFERENCE_TOKENS__ = '+json.dumps(colors,separators=(',',':'))+';\nif(typeof module !== "undefined") module.exports=global.__GENUI_REFERENCE_TOKENS__; })(typeof window === "undefined" ? globalThis : window);\n')

    def archive(data):
        magic, length = struct.unpack_from('<II', data)
        assert magic == 0x0100c633
        offset, end, result = 8, 8+length, {}
        while offset < end:
            fields = []
            for _ in range(2):
                raw, = struct.unpack_from('<I',data,offset);offset += 4
                size = raw & 0x7fffffff
                fields.append(data[offset:offset+size]);offset += size
                if raw >> 31: offset += (-size)%4
            result[fields[0].decode()] = fields[1]
        assert offset == end
        return result

    packed = subprocess.run(['zstd','-d','-q','-c',str(modules/'dil_icon_assets.valdimodule/res.assetpackage')],capture_output=True,check=True).stdout
    files = archive(archive(packed)['0.0'])
    def element(node):
        return {'tag':node.tag.split('}')[-1],'attrs':node.attrib,'children':[element(child) for child in node]}
    icons = {Path(name).stem.replace('_','-'):element(ET.fromstring(value)) for name,value in files.items() if name.endswith('.svg')}
    aliases = json.loads(export('dil_widgets.valdimodule','src__widgets__LucideIconAliases.js').splitlines()[-1])
    assert len(icons) == 2511
    (assets/'reference-icons.js').write_text('/* Exact SVG assets and Lucide aliases from the supplied dil_icon_assets module. */\n(function(global) { global.__GENUI_REFERENCE_ICONS__ = '+json.dumps({'icons':icons,**aliases},separators=(',',':'))+';\nif(typeof module !== "undefined") module.exports=global.__GENUI_REFERENCE_ICONS__; })(typeof window === "undefined" ? globalThis : window);\n')
    print(f'Recovered {len(sources)} components and {len(icons)} SVGs')

# Exact self-contained CEL and pure SVG rendering exports.
module_output = ios / 'YamabikoChat/Features/Tools/GenUI/NativeCEL/GenUICELModules.h'
original_modules = [('cel', path) for path in sorted((modules/'cel.valdimodule').glob('*.js'))]
extra = [('dil_charts','src__widgets__SvgChart.js'),('dil_core','src__colors__DILColor.js'),('dil_core','src__colors__DILColorsDefinition.js'),('dil_core','src__colors__DILColorsInit.js'),('dil_core','src__colors__DILSemanticColorRegistry.js'),('dil_core','src__layout__DILLayout.js'),('dil_core','src__layout__DILSpacing.js'),('dil_core','src__utils__AttributeParser.js'),('dil_core','src__utils__XmlBuilder.js'),('dil_charts','src__widgets__PieChart.js')]
original_modules += [(module,modules/(module+'.valdimodule')/filename) for module,filename in extra]
lines = ['/* Exact CEL and pure SVG rendering modules from the supplied analysis. */', '#include <stddef.h>', 'typedef struct { const char *name; const unsigned char *data; size_t length; } GenUICELModule;']
entries = []
for index, (module,path) in enumerate(original_modules):
    data = path.read_bytes()
    assert data[:4] == bytes.fromhex('34c60001')
    data = data[4:]
    lines.append('static const unsigned char cel_module_'+str(index)+'[] = {'+','.join(str(byte) for byte in data)+'};')
    entries.append((module+'/'+path.name[:-3].replace('__','/'),index,len(data)))
lines.append('static const GenUICELModule cel_modules[] = {')
for name,index,length in entries: lines.append('{"'+name+'",cel_module_'+str(index)+','+str(length)+'},')
lines.append('};')
module_output.write_text('\n'.join(lines))
