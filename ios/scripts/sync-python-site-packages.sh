#!/usr/bin/env bash
set -euo pipefail

if [[ "$#" -ne 2 ]]; then
  echo "Usage: $0 SOURCE_DIRECTORY DESTINATION_DIRECTORY" >&2
  exit 1
fi

source_directory="$1"
destination_directory="$2"

if [[ ! -d "$source_directory" ]]; then
  echo "Python site-packages source is missing: $source_directory" >&2
  exit 1
fi

mkdir -p "$destination_directory"

# --delete-excluded is required for incremental builds: --exclude alone also
# protects a static archive left by an earlier build from --delete.
rsync -au --delete --delete-excluded --exclude '*.a' \
  "$source_directory/" \
  "$destination_directory/"
