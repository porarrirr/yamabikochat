#!/usr/bin/env bash
set -euo pipefail

test_root="$(mktemp -d)"
trap 'rm -rf "$test_root"' EXIT

source_directory="$test_root/source"
destination_directory="$test_root/destination"
mkdir -p "$source_directory/package/lib" "$destination_directory/package/lib"

printf 'current\n' > "$source_directory/package/module.py"
printf 'must not ship\n' > "$source_directory/package/lib/source-static.a"
printf 'stale\n' > "$destination_directory/package/lib/libnpymath.a"
printf 'obsolete\n' > "$destination_directory/package/obsolete.py"

"$(dirname "$0")/sync-python-site-packages.sh" \
  "$source_directory" \
  "$destination_directory"

test -f "$destination_directory/package/module.py"
test ! -e "$destination_directory/package/lib/source-static.a"
test ! -e "$destination_directory/package/lib/libnpymath.a"
test ! -e "$destination_directory/package/obsolete.py"

echo "Python site-packages sync test passed"
