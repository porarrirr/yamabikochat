#!/usr/bin/env python3
"""Generate the embedded fallback from the bundled renderer. Use --check in CI."""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "YamabikoChat/App/Resources/mathjax/markdown-renderer.js"
target = root / "YamabikoChat/Features/Chat/MathMarkdownRendererSource.generated.swift"
# A raw literal preserves JS escapes; indentation matches Swift multiline rules.
script = source.read_text()
delimiter = "#"
while '"""' + delimiter in script or "\\" + delimiter + "(" in script:
    delimiter += "#"
output = (
    "// Generated by scripts/generate-markdown-renderer.py. Do not edit.\n"
    "enum MathMarkdownRendererSource {\n"
    + "    static let script = " + delimiter + '"""\n'
    + "".join("    " + line + "\n" for line in script.split("\n"))
    + '    """' + delimiter + "\n}\n"
)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != output:
        parser.exit(1, "Renderer is stale. Run python3 scripts/generate-markdown-renderer.py\n")
elif not target.exists() or target.read_text() != output:
    target.write_text(output)
